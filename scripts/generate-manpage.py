"""Generate Unix manpage (agtmls.1) for the agtmls CLI."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAN_FILE = ROOT / "share" / "man" / "man1" / "agtmls.1"

sys.path.insert(0, str(ROOT / "scripts"))
from _lib.cli_parser import build_parser  # noqa: E402  (scripts path first)

HEADER = """.\\" SPDX-FileCopyrightText: 2026 Sebastien Rousseau
.\\" SPDX-License-Identifier: Apache-2.0 OR MIT
.\\" Generated by scripts/generate-manpage.py from the argument parser; do not edit.
.TH AGTMLS 1 "{date}" "agtmls {version}" "User Commands"
.SH NAME
agtmls \\- verified registry and installer for AI-agent skills
.SH SYNOPSIS
.B agtmls
[\\fB\\-\\-version\\fR]
.I command
[\\fIoptions\\fR]
.SH DESCRIPTION
\\fBagtmls\\fR validates, indexes, audits, exports and installs agent skills,
prompts, commands and subagents. Each skill is content-addressed, the index is
signed, and an install is recorded in a lockfile that \\fBverify\\fR checks.
.SH COMMANDS
"""

FOOTER = """.SH SEE ALSO
The command-line reference, docs/cli.md, in the AgtMLS repository:
https://github.com/sebastienrousseau/agtmls
.SH AUTHORS
Sebastien Rousseau
.SH COPYRIGHT
Apache-2.0 OR MIT
"""


def roff(text: str) -> str:
    """Escape text for roff: backslashes, hyphens, and a leading dot or quote."""
    text = text.replace("\\", "\\e").replace("-", "\\-")
    return "\\&" + text if text[:1] in (".", "'") else text


def subcommands():
    """(name, synopsis, help) for every subcommand, in the parser's order."""
    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))  # noqa: SLF001
    helps = {choice.dest: choice.help or "" for choice in sub._choices_actions}  # noqa: SLF001
    for name, child in sub.choices.items():
        usage = " ".join(child.format_usage().split())
        synopsis = usage.split(f" {name}", 1)[1].strip() if f" {name}" in usage else ""
        yield name, synopsis, helps.get(name, "")


def release_date(version: str) -> str:
    """The CHANGELOG date of `version`, so the page changes only with a release."""
    path = ROOT / "CHANGELOG.md"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    match = re.search(rf"^## {re.escape(version)} - (\d{{4}}-\d{{2}}-\d{{2}})$", text, re.MULTILINE)
    return match.group(1) if match else ""


def rendered() -> str:
    """The manpage. Version from plugin.json, commands from the parser: each
    was hand-copied once, and the copy covered 11 of 37 commands."""
    version = json.loads(
        (ROOT / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8")
    )["version"]
    out = [HEADER.format(date=release_date(version), version=version)]
    for name, synopsis, text in subcommands():
        out.append(f".TP\n\\fB{name}\\fR {roff(synopsis)}\n{roff(text)}.\n")
    out.append(FOOTER)
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write manpage to share/man/man1/agtmls.1")
    parser.add_argument("--check", action="store_true", help="verify manpage is up to date")
    args = parser.parse_args()

    if args.write:
        MAN_FILE.parent.mkdir(parents=True, exist_ok=True)
        MAN_FILE.write_text(rendered(), encoding="utf-8")
        print(f"wrote {MAN_FILE.relative_to(ROOT)}")
        return 0

    if args.check:
        if not MAN_FILE.exists() or MAN_FILE.read_text(encoding="utf-8") != rendered():
            print(f"FAIL: stale manpage at {MAN_FILE.relative_to(ROOT)} (run generate-manpage.py --write)", file=sys.stderr)
            return 1
        print("OK: manpage is current")
        return 0

    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
