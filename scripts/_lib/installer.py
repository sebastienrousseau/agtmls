"""Cross-platform workspace installation for coding agents.

Configures target workspaces with AgtMLS skills, slash commands, agent
definitions, and auto-loaded system prompts across native agent runtimes.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

from _lib import aider_conf, skill_roots

AGENT_CONFIGS: dict[str, tuple[str, str]] = {
    "claude": (".claude", "CLAUDE.md"),
    "aider": (".aider", "CONVENTIONS.md"),
    "codex": (".codex", "AGENTS.md"),
    "antigravity": (".agents", "AGENTS.md"),
    "agy": (".agents", "AGENTS.md"),
}


def agent_config(agent: str) -> tuple[str, str]:
    """Map agent identifier to (dot_dir, prompt_filename)."""
    cfg = AGENT_CONFIGS.get(agent)
    if cfg is None:
        raise ValueError(f"Unknown agent CLI: '{agent}'")
    return cfg


def prompt_is_ours(prompt_path: Path) -> bool:
    """True if prompt file exists and carries the AgtMLS generator marker."""
    if not prompt_path.is_file():
        return False
    try:
        first = prompt_path.read_text(encoding="utf-8", errors="replace").splitlines()[
            :1
        ]
        return bool(first and "Generated by AgtMLS" in first[0])
    except OSError:
        return False


def backup_prompt(prompt_path: Path, dry_run: bool) -> Path:
    """Create timestamped backup of existing user prompt file."""
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup_path = prompt_path.with_name(f"{prompt_path.name}.agtmls-backup.{timestamp}")
    if dry_run:
        print(f"   [dry-run] would back up {prompt_path.name} → {backup_path.name}")
    else:
        shutil.copy2(prompt_path, backup_path)
        print(f"💾 Backed up your existing {prompt_path.name} → {backup_path.name}")
    return backup_path


def assemble_prompt(root: Path, language: str) -> tuple[str, str]:
    """Assemble system prompt content from base and language profile."""
    base_file = root / "system-prompts" / "_base.md"
    base_text = base_file.read_text(encoding="utf-8") if base_file.exists() else ""
    lang_file = root / "system-prompts" / f"{language}.md"
    has_lang = lang_file.is_file()
    profile = f"$LANGUAGE.md ({language}.md)" if has_lang else "_base.md only"
    header = (
        "<!-- Generated by AgtMLS setup-workspace.sh — do not edit here.\n"
        f"     Edit the hub (system-prompts/_base.md + {language}.md) and re-run. -->\n\n"
    )
    content = header + base_text + "\n\n"
    if has_lang:
        content += lang_file.read_text(encoding="utf-8")
    return content, profile


def _git_exclude_path(target: Path) -> Path | None:
    """Find .git/info/exclude in target repository if present."""
    dot_git = target / ".git"
    if dot_git.is_dir():
        return dot_git / "info" / "exclude"
    if dot_git.is_file():
        try:
            line = dot_git.read_text(encoding="utf-8").strip()
            if line.startswith("gitdir:"):
                gitdir = Path(line.split(":", 1)[1].strip())
                resolved = (
                    (target / gitdir).resolve() if not gitdir.is_absolute() else gitdir
                )
                return resolved / "info" / "exclude"
        except OSError:
            pass
    return None


def _target_patterns(
    cli_dir: str, sys_path: str, agent: str, skills_only: bool
) -> list[str]:
    patterns = [f"{cli_dir}/", ".agtmls/"]
    if not skills_only:
        patterns.append(sys_path)
        if agent == "aider":
            patterns.append(".aider.conf.yml")
    return patterns


def _read_existing_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines() if path.is_file() else []


def _prune_skills_only(existing: list[str], sys_path: str) -> list[str]:
    dropped = {sys_path, ".aider.conf.yml"}
    return [line for line in existing if line not in dropped]


def update_git_exclude(
    target: Path,
    cli_dir: str,
    sys_path: str,
    agent: str,
    skills_only: bool,
    dry_run: bool,
) -> None:
    """Update target repository .git/info/exclude with hub artifacts."""
    exclude = _git_exclude_path(target)
    if exclude is None or dry_run:
        return
    exclude.parent.mkdir(parents=True, exist_ok=True)
    existing = _read_existing_lines(exclude)
    original = list(existing)
    if skills_only:
        existing = _prune_skills_only(existing, sys_path)
    patterns = _target_patterns(cli_dir, sys_path, agent, skills_only)
    additions = [p for p in patterns if p not in existing]
    combined = existing + additions
    if combined != original:
        exclude.write_text("\n".join(combined) + "\n", encoding="utf-8")


def link_or_copy(src: Path, dst: Path, copy: bool, dry_run: bool) -> None:
    """Link source to destination with automatic copy fallback on Windows/privilege errors."""
    if dry_run:
        action = "copy" if copy else "link"
        print(f"   [dry-run] {action} {dst.name} → {src}")
        return
    if dst.is_symlink() or dst.is_file():
        dst.unlink()
    elif dst.is_dir():
        shutil.rmtree(dst)
    if copy:
        shutil.copytree(src, dst) if src.is_dir() else shutil.copy2(src, dst)
    else:
        try:
            dst.symlink_to(src, target_is_directory=src.is_dir())
        except OSError:
            shutil.copytree(src, dst) if src.is_dir() else shutil.copy2(src, dst)


def install_skills(
    root: Path,
    skills_dir: Path,
    copy: bool,
    dry_run: bool,
    bundles: set[str],
) -> int:
    """Install general and requested bundle skills into skills directory."""
    linked = 0
    for skill_path in skill_roots.skill_dirs(root):
        meta_file = skill_path / "metadata.json"
        bundle = None
        if meta_file.is_file():
            try:
                bundle = json.loads(meta_file.read_text(encoding="utf-8")).get("bundle")
            except (json.JSONDecodeError, OSError):
                pass
        if bundle is None or bundle in bundles:
            link_or_copy(skill_path, skills_dir / skill_path.name, copy, dry_run)
            linked += 1
    return linked


def install_agents(root: Path, agents_dir: Path, copy: bool, dry_run: bool) -> int:
    """Install agent definition markdown files into agents directory."""
    linked = 0
    agents_src = root / "agents"
    if agents_src.is_dir():
        for agent_file in sorted(agents_src.glob("*.md")):
            link_or_copy(agent_file, agents_dir / agent_file.name, copy, dry_run)
            linked += 1
    return linked


def install_commands(root: Path, commands_dir: Path, copy: bool, dry_run: bool) -> int:
    """Install slash command markdown files into commands directory."""
    linked = 0
    commands_src = root / "commands"
    if commands_src.is_dir():
        for cmd_file in sorted(commands_src.iterdir()):
            if (
                cmd_file.is_file()
                and cmd_file.name != "README.md"
                and not cmd_file.name.startswith(".")
            ):
                link_or_copy(cmd_file, commands_dir / cmd_file.name, copy, dry_run)
                linked += 1
    return linked


def _clean_skills_only_prompt(
    prompt_path: Path, prompt_file: str, dry_run: bool
) -> None:
    if prompt_is_ours(prompt_path):
        if dry_run:
            print(f"   [dry-run] remove {prompt_file}")
        else:
            prompt_path.unlink()
            print(f"🧹 Removed the AgtMLS-generated {prompt_file} (skills-only)")


def _refuse_foreign_prompt(prompt_path: Path, prompt_file: str, target: Path) -> None:
    print(
        f"❌ {prompt_file} exists in {target} and was not generated by AgtMLS.",
        file=sys.stderr,
    )
    print("   Refusing to overwrite your file. Choose one:", file=sys.stderr)
    print(
        f"     --skills-only  install skills, leave {prompt_file} untouched",
        file=sys.stderr,
    )
    print("     --force        back it up, then overwrite", file=sys.stderr)
    print(
        "     --dry-run      show every change this command would make", file=sys.stderr
    )


def _register_aider(target: Path, dry_run: bool) -> None:
    if dry_run:
        print("   [dry-run] register CONVENTIONS.md under read: in .aider.conf.yml")
        return
    conf_path = target / ".aider.conf.yml"
    text = conf_path.read_text(encoding="utf-8") if conf_path.is_file() else ""
    new, message = aider_conf.register(text, "CONVENTIONS.md")
    if new is not None:
        conf_path.write_text(new, encoding="utf-8")
    print(f"🔧 .aider.conf.yml: {message}")


def _ensure_prompt_writable(
    prompt_path: Path, prompt_file: str, target: Path, force: bool, dry_run: bool
) -> int:
    if not prompt_path.is_file() or prompt_is_ours(prompt_path):
        return 0
    if not force:
        _refuse_foreign_prompt(prompt_path, prompt_file, target)
        return 1
    backup_prompt(prompt_path, dry_run)
    return 0


def _write_prompt_content(
    prompt_path: Path, prompt_file: str, root: Path, language: str, dry_run: bool
) -> None:
    if dry_run:
        print(f"   [dry-run] write {prompt_file}")
        return
    content, _ = assemble_prompt(root, language)
    prompt_path.write_text(content, encoding="utf-8")


def _handle_prompt(
    root: Path,
    target: Path,
    language: str,
    agent: str,
    prompt_file: str,
    skills_only: bool,
    force: bool,
    dry_run: bool,
) -> int:
    """Handle prompt assembly, backup, or removal."""
    prompt_path = target / prompt_file
    if skills_only:
        _clean_skills_only_prompt(prompt_path, prompt_file, dry_run)
        return 0

    rc = _ensure_prompt_writable(prompt_path, prompt_file, target, force, dry_run)
    if rc != 0:
        return rc

    _write_prompt_content(prompt_path, prompt_file, root, language, dry_run)
    if agent == "aider":
        _register_aider(target, dry_run)
    return 0


def install_workspace(
    root: Path,
    target: Path,
    language: str,
    agent: str,
    skills_only: bool = False,
    copy: bool = False,
    force: bool = False,
    dry_run: bool = False,
    bundles: list[str] | None = None,
) -> int:
    """Execute complete workspace setup for specified language and agent."""
    try:
        cli_dir, prompt_file = agent_config(agent)
    except ValueError as exc:
        print(f"❌ {exc}", file=sys.stderr)
        print(
            "   Supported: claude | aider | codex | antigravity (agy)", file=sys.stderr
        )
        return 1

    rc = _handle_prompt(
        root, target, language, agent, prompt_file, skills_only, force, dry_run
    )
    if rc != 0:
        return rc

    cli_path = target / cli_dir
    skills_dir = cli_path / "skills"
    commands_dir = cli_path / "commands"
    agents_dir = cli_path / "agents"

    if not dry_run:
        skills_dir.mkdir(parents=True, exist_ok=True)
        commands_dir.mkdir(parents=True, exist_ok=True)
        agents_dir.mkdir(parents=True, exist_ok=True)

    update_git_exclude(target, cli_dir, prompt_file, agent, skills_only, dry_run)
    bundle_set = set(bundles or [])

    linked_skills = install_skills(root, skills_dir, copy, dry_run, bundle_set)
    linked_agents = install_agents(root, agents_dir, copy, dry_run)
    install_commands(root, commands_dir, copy, dry_run)

    action = "copied" if copy else "linked"
    print(f"   {action} {linked_skills} skill(s)")
    if linked_agents:
        print(f"   + {linked_agents} agent(s)")
    for b in sorted(bundle_set):
        print(f"   + bundle: {b}")

    if skills_only:
        print(
            f"✅ AgtMLS setup complete (skills-only): skills → {cli_dir}/skills/. No system prompt written."
        )
    else:
        print(
            f"✅ AgtMLS setup complete: system prompt → {prompt_file}, skills → {cli_dir}/skills/."
        )
    return 0


def build_parser() -> argparse.ArgumentParser:
    """Build command line argument parser for workspace installer."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("language", help="Target programming language")
    parser.add_argument("agent", help="Target coding agent runtime")
    parser.add_argument(
        "--skills-only",
        action="store_true",
        help="Install skills only; do not write system prompt",
    )
    parser.add_argument(
        "--copy", action="store_true", help="Copy skills instead of symlinking"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Back up and overwrite existing prompt file",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print planned changes without touching disk",
    )
    parser.add_argument(
        "--bundle", action="append", default=[], help="Include project skill bundle"
    )
    return parser


def run_argv(argv: list[str], cwd: Path, root: Path) -> int:
    """Parse argv and invoke install_workspace."""
    parser = build_parser()
    args = parser.parse_args(argv)
    return install_workspace(
        root=root,
        target=cwd,
        language=args.language,
        agent=args.agent,
        skills_only=args.skills_only,
        copy=args.copy,
        force=args.force,
        dry_run=args.dry_run,
        bundles=args.bundle,
    )
