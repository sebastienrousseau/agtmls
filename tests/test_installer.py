"""Tests for the native cross-platform workspace installer (_lib.installer)."""

from __future__ import annotations

import io
import json
import shutil
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest import mock

from .support import ROOT

sys.path.insert(0, str(ROOT / "scripts"))

from _lib import installer

from .mini_registry import mini_registry


class InstallerTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="agtmls-installer-")).resolve()
        self.addCleanup(lambda: shutil.rmtree(self.tmp, ignore_errors=True))
        self.root = mini_registry(self.tmp / "registry")
        self.target = self.tmp / "workspace"
        self.target.mkdir()

    def test_agent_config_resolution(self) -> None:
        self.assertEqual(installer.agent_config("claude"), (".claude", "CLAUDE.md"))
        self.assertEqual(installer.agent_config("aider"), (".aider", "CONVENTIONS.md"))
        self.assertEqual(installer.agent_config("codex"), (".codex", "AGENTS.md"))
        self.assertEqual(
            installer.agent_config("antigravity"), (".agents", "AGENTS.md")
        )
        self.assertEqual(installer.agent_config("agy"), (".agents", "AGENTS.md"))
        with self.assertRaises(ValueError):
            installer.agent_config("nonexistent")

    def test_prompt_is_ours(self) -> None:
        missing = self.target / "CLAUDE.md"
        self.assertFalse(installer.prompt_is_ours(missing))

        foreign = self.target / "FOREIGN.md"
        foreign.write_text("# Hand authored\n", encoding="utf-8")
        self.assertFalse(installer.prompt_is_ours(foreign))

        ours = self.target / "OURS.md"
        ours.write_text(
            "<!-- Generated by AgtMLS setup-workspace.sh -->\n", encoding="utf-8"
        )
        self.assertTrue(installer.prompt_is_ours(ours))

        with mock.patch.object(Path, "read_text", side_effect=OSError("unreadable")):
            self.assertFalse(installer.prompt_is_ours(ours))

    def test_backup_prompt(self) -> None:
        prompt = self.target / "CLAUDE.md"
        prompt.write_text("user content", encoding="utf-8")

        # Dry run
        backup_dry = installer.backup_prompt(prompt, dry_run=True)
        self.assertFalse(backup_dry.exists())

        # Live backup
        backup_live = installer.backup_prompt(prompt, dry_run=False)
        self.assertTrue(backup_live.is_file())
        self.assertEqual(backup_live.read_text(encoding="utf-8"), "user content")

    def test_assemble_prompt(self) -> None:
        content_py, profile_py = installer.assemble_prompt(self.root, "python")
        self.assertIn("Generated by AgtMLS", content_py)
        self.assertIn("python.md", profile_py)

        content_unk, profile_unk = installer.assemble_prompt(self.root, "unknown_lang")
        self.assertIn("Generated by AgtMLS", content_unk)
        self.assertEqual(profile_unk, "_base.md only")

        # Base missing
        base = self.root / "system-prompts" / "_base.md"
        if base.exists():
            base.unlink()
        content_no_base, _ = installer.assemble_prompt(self.root, "unknown_lang")
        self.assertTrue(content_no_base.startswith("<!-- Generated by AgtMLS"))

    def test_git_exclude_handling(self) -> None:
        # Not a git repo
        installer.update_git_exclude(
            self.target, ".claude", "CLAUDE.md", "claude", False, False
        )

        # Standard .git directory
        git_dir = self.target / ".git"
        git_dir.mkdir()
        installer.update_git_exclude(
            self.target, ".claude", "CLAUDE.md", "claude", False, False
        )
        exclude = git_dir / "info" / "exclude"
        self.assertTrue(exclude.is_file())
        text = exclude.read_text(encoding="utf-8")
        self.assertIn(".claude/", text)
        self.assertIn("CLAUDE.md", text)
        self.assertIn(".agtmls/", text)

        # Aider includes .aider.conf.yml
        installer.update_git_exclude(
            self.target, ".aider", "CONVENTIONS.md", "aider", False, False
        )
        text_aider = exclude.read_text(encoding="utf-8")
        self.assertIn(".aider.conf.yml", text_aider)

        # Dry run does not mutate
        installer.update_git_exclude(
            self.target, ".codex", "AGENTS.md", "codex", False, True
        )

        # Skills only prunes prompt
        installer.update_git_exclude(
            self.target, ".claude", "CLAUDE.md", "claude", True, False
        )
        text_pruned = exclude.read_text(encoding="utf-8")
        self.assertNotIn("CLAUDE.md", text_pruned.splitlines())

        # Worktree gitdir file
        sub = self.tmp / "subworktree"
        sub.mkdir()
        real_git = self.tmp / "real_git"
        real_git.mkdir()
        (sub / ".git").write_text(f"gitdir: {real_git}\n", encoding="utf-8")
        installer.update_git_exclude(
            sub, ".claude", "CLAUDE.md", "claude", False, False
        )
        self.assertTrue((real_git / "info" / "exclude").is_file())

        # Unreadable .git file
        bad_sub = self.tmp / "bad_sub"
        bad_sub.mkdir()
        bad_git = bad_sub / ".git"
        bad_git.write_text("corrupt\n", encoding="utf-8")
        installer.update_git_exclude(
            bad_sub, ".claude", "CLAUDE.md", "claude", False, False
        )

    def test_link_or_copy(self) -> None:
        src = self.tmp / "source.txt"
        src.write_text("source file", encoding="utf-8")
        dst = self.target / "dest.txt"

        # Dry run
        installer.link_or_copy(src, dst, copy=False, dry_run=True)
        self.assertFalse(dst.exists())

        # Symlink
        installer.link_or_copy(src, dst, copy=False, dry_run=False)
        self.assertTrue(dst.is_symlink())
        self.assertEqual(dst.read_text(encoding="utf-8"), "source file")

        # Replace with copy
        installer.link_or_copy(src, dst, copy=True, dry_run=False)
        self.assertTrue(dst.is_file())
        self.assertFalse(dst.is_symlink())

        # Symlink failure fallback to copy
        src_dir = self.tmp / "src_dir"
        src_dir.mkdir()
        dst_dir = self.target / "dst_dir"
        with mock.patch.object(
            Path, "symlink_to", side_effect=OSError("privilege not held")
        ):
            installer.link_or_copy(src_dir, dst_dir, copy=False, dry_run=False)
            self.assertTrue(dst_dir.is_dir())
            self.assertFalse(dst_dir.is_symlink())

    def test_install_workspace_lifecycle(self) -> None:
        # Full install
        rc = installer.install_workspace(
            root=self.root,
            target=self.target,
            language="python",
            agent="claude",
            skills_only=False,
            copy=False,
            force=False,
            dry_run=False,
        )
        self.assertEqual(rc, 0)
        self.assertTrue((self.target / "CLAUDE.md").is_file())
        self.assertTrue(
            (self.target / ".claude" / "skills" / "using-agtmls").is_symlink()
        )
        self.assertTrue(
            (self.target / ".claude" / "commands" / "agtmls-audit.md").is_symlink()
        )

        # Skills-only cleans generated prompt
        rc_skills = installer.install_workspace(
            root=self.root,
            target=self.target,
            language="python",
            agent="claude",
            skills_only=True,
            copy=False,
            force=False,
            dry_run=False,
        )
        self.assertEqual(rc_skills, 0)
        self.assertFalse((self.target / "CLAUDE.md").exists())

        # Dry run
        rc_dry = installer.install_workspace(
            root=self.root,
            target=self.target,
            language="python",
            agent="claude",
            skills_only=False,
            copy=True,
            force=False,
            dry_run=True,
        )
        self.assertEqual(rc_dry, 0)

        # Unknown agent
        buf = io.StringIO()
        with redirect_stderr(buf):
            rc_unk = installer.install_workspace(
                root=self.root,
                target=self.target,
                language="python",
                agent="unknown_agent",
            )
        self.assertEqual(rc_unk, 1)

    def test_refuse_foreign_prompt_unless_force(self) -> None:
        prompt = self.target / "CLAUDE.md"
        prompt.write_text("# Foreign Prompt\n", encoding="utf-8")

        # Refusal
        buf = io.StringIO()
        with redirect_stderr(buf):
            rc = installer.install_workspace(
                root=self.root,
                target=self.target,
                language="python",
                agent="claude",
                force=False,
            )
        self.assertEqual(rc, 1)
        self.assertIn("refusing to overwrite", buf.getvalue().lower())

        # Force overwrite
        rc_force = installer.install_workspace(
            root=self.root,
            target=self.target,
            language="python",
            agent="claude",
            force=True,
        )
        self.assertEqual(rc_force, 0)
        self.assertTrue(installer.prompt_is_ours(prompt))
        backups = list(self.target.glob("CLAUDE.md.agtmls-backup.*"))
        self.assertEqual(len(backups), 1)

