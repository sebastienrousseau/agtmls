    def test_link_or_copy_over_directory_and_file(self) -> None:
        src = self.tmp / "src_file.txt"
        src.write_text("data", encoding="utf-8")
        dst = self.target / "existing_dir"
        dst.mkdir()
        (dst / "sub.txt").write_text("old", encoding="utf-8")
        installer.link_or_copy(src, dst, copy=True, dry_run=False)
        self.assertTrue(dst.is_file())

        dst_file = self.target / "existing_file.txt"
        dst_file.write_text("old file", encoding="utf-8")
