    def test_skill_bundle_filtering_and_bad_metadata(self) -> None:
        skills_dir = self.root / "skills"
        special = skills_dir / "special-skill"
        special.mkdir()
        (special / "SKILL.md").write_text("# Special\n", encoding="utf-8")
        (special / "metadata.json").write_text(
            json.dumps({"bundle": "extra"}), encoding="utf-8"
        )

        corrupt = skills_dir / "corrupt-skill"
        corrupt.mkdir()
        (corrupt / "SKILL.md").write_text("# Corrupt\n", encoding="utf-8")
        (corrupt / "metadata.json").write_text("{bad json", encoding="utf-8")

        target_skills = self.target / ".claude" / "skills"
        target_skills.mkdir(parents=True)
        # Without extra bundle -> special-skill is skipped, corrupt-skill has bundle=None so included
        installer.install_skills(
            self.root, target_skills, copy=True, dry_run=False, bundles=set()
        )
        self.assertFalse((target_skills / "special-skill").exists())
        self.assertTrue((target_skills / "corrupt-skill").exists())

